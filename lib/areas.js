// 由字串找出符合的區名(完全比對優先,其次包含)
export function matchArea(query) {
  const q = query.trim();
  if (!q) return null;
  if (AREA_CENTERS[q]) return q;
  for (const area of Object.keys(AREA_CENTERS)) {
    if (area.includes(q) || q.includes(area.replace(/區$/, ''))) return area;
  }
  return null;
}
